//! Explicit uploads only; credentials are never printed or included in recordings.
use crate::{
    config,
    export::{self, Activity},
};
use anyhow::{anyhow, bail, Context, Result};
use fs2::FileExt;
use reqwest::{Client, RequestBuilder};
use serde_json::{json, Value};
use std::{fs, path::Path, time::Duration};
fn env(name: &str) -> Result<String> {
    std::env::var(name).map_err(|_| anyhow!("{name} is required"))
}
fn client() -> Result<Client> {
    Ok(Client::builder()
        .timeout(Duration::from_secs(20))
        .redirect(reqwest::redirect::Policy::none())
        .build()?)
}
async fn response(request: RequestBuilder) -> Result<Value> {
    let r = request
        .send()
        .await
        .map_err(|_| anyhow!("Strava request failed; sensitive network details hidden"))?;
    if !r.status().is_success() {
        bail!(
            "Strava returned HTTP {}; response body hidden",
            r.status().as_u16()
        );
    }
    r.json()
        .await
        .map_err(|_| anyhow!("invalid Strava response"))
}
fn token_path(dir: &Path) -> std::path::PathBuf {
    dir.join("strava-tokens.json")
}
pub async fn auth(dir: &Path, exchange: bool) -> Result<()> {
    let id = env("SUNNY_STRAVA_CLIENT_ID")?;
    if !exchange {
        let mut url = reqwest::Url::parse("https://www.strava.com/oauth/authorize")?;
        url.query_pairs_mut()
            .append_pair("client_id", &id)
            .append_pair(
                "redirect_uri",
                &std::env::var("SUNNY_STRAVA_REDIRECT_URI")
                    .unwrap_or_else(|_| "http://localhost".into()),
            )
            .append_pair("response_type", "code")
            .append_pair("approval_prompt", "auto")
            .append_pair("scope", "activity:write");
        println!("Open this URL, authorize, then set SUNNY_STRAVA_CODE from the redirect and run strava-auth --exchange:\n{url}");
        return Ok(());
    }
    let secret = env("SUNNY_STRAVA_CLIENT_SECRET")?;
    let code = env("SUNNY_STRAVA_CODE")?;
    let value = response(client()?.post("https://www.strava.com/oauth/token").form(&[
        ("client_id", id),
        ("client_secret", secret),
        ("code", code),
        ("grant_type", "authorization_code".into()),
    ]))
    .await?;
    save_tokens(dir, &value)?;
    println!("Strava authorization saved privately. Uploads happen only when you run sync.");
    Ok(())
}
fn save_tokens(dir: &Path, v: &Value) -> Result<()> {
    if v["access_token"].as_str().is_none()
        || v["refresh_token"].as_str().is_none()
        || v["expires_at"].as_i64().is_none()
    {
        bail!("Strava token response missing required fields");
    }
    config::write_private(
        &token_path(dir),
        &serde_json::to_vec(
            &json!({"access_token":v["access_token"],"refresh_token":v["refresh_token"],"expires_at":v["expires_at"]}),
        )?,
    )
}
async fn access(dir: &Path, client: &Client) -> Result<String> {
    if let Ok(token) = std::env::var("SUNNY_STRAVA_ACCESS_TOKEN") {
        return Ok(token);
    }
    let mut token: Value = serde_json::from_slice(
        &fs::read(token_path(dir))
            .context("authorize Strava first or set SUNNY_STRAVA_ACCESS_TOKEN")?,
    )
    .map_err(|_| anyhow!("invalid private Strava token file"))?;
    if token["expires_at"].as_i64().unwrap_or(0) <= chrono::Utc::now().timestamp() + 60 {
        let refresh = token["refresh_token"]
            .as_str()
            .context("Strava refresh token unavailable")?
            .to_owned();
        token = response(client.post("https://www.strava.com/oauth/token").form(&[
            ("client_id", env("SUNNY_STRAVA_CLIENT_ID")?),
            ("client_secret", env("SUNNY_STRAVA_CLIENT_SECRET")?),
            ("grant_type", "refresh_token".into()),
            ("refresh_token", refresh),
        ]))
        .await?;
        save_tokens(dir, &token)?;
    }
    Ok(token["access_token"]
        .as_str()
        .context("Strava access token unavailable")?
        .into())
}
pub async fn sync(dir: &Path, input: &Path, name: Option<&str>) -> Result<()> {
    let activity = Activity::from_rows(&export::read(input)?)?;
    // IDs generated by this application are UUIDs; never turn untrusted file contents into paths.
    let id = uuid::Uuid::parse_str(&activity.id).context("upload session ID must be a UUID")?;
    let receipts = dir.join("strava-uploads");
    config::private_dir(&receipts)?;
    let lock = fs::OpenOptions::new()
        .create(true)
        .truncate(false)
        .write(true)
        .open(receipts.join("upload.lock"))?;
    lock.try_lock_exclusive()
        .context("another Strava upload is running")?;
    let path = receipts.join(format!("{id}.json"));
    let client = client()?;
    let previous: Option<Value> = if path.exists() {
        Some(serde_json::from_slice(&fs::read(&path)?)?)
    } else {
        None
    };
    if previous
        .as_ref()
        .is_some_and(|v| v["activity_id"].as_u64().is_some())
    {
        println!("This session is already synchronized.");
        return Ok(());
    }
    if previous
        .as_ref()
        .is_some_and(|v| v["upload_id"].as_u64().is_none())
    {
        bail!("an earlier upload has an uncertain outcome; check your Strava activities before removing its private upload receipt to retry");
    }
    let token = access(dir, &client).await?;
    let upload = if let Some(v) = previous {
        v["upload_id"].as_u64().unwrap()
    } else {
        let bytes = activity.fit()?;
        let form = reqwest::multipart::Form::new()
            .text("data_type", "fit")
            .text("trainer", "true")
            .text("sport_type", "Ride")
            .text("external_id", activity.id.clone())
            .text("name", name.unwrap_or("SunnyFit indoor cycling").to_owned())
            .part(
                "file",
                reqwest::multipart::Part::bytes(bytes)
                    .file_name("indoor-cycling.fit")
                    .mime_str("application/octet-stream")?,
            );
        config::write_private(
            &path,
            &serde_json::to_vec(&json!({"session_id":id.to_string(),"state":"submitting"}))?,
        )?;
        let value = response(
            client
                .post("https://www.strava.com/api/v3/uploads")
                .bearer_auth(&token)
                .multipart(form),
        )
        .await?;
        let upload = value["id"].as_u64().context(
            "Strava did not acknowledge an upload ID; check your activities before retrying",
        )?;
        config::write_private(
            &path,
            &serde_json::to_vec(
                &json!({"session_id":id.to_string(),"upload_id":upload,"state":"processing"}),
            )?,
        )?;
        upload
    };
    for _ in 0..5 {
        let v = response(
            client
                .get(format!("https://www.strava.com/api/v3/uploads/{upload}"))
                .bearer_auth(&token),
        )
        .await?;
        if let Some(activity_id) = v["activity_id"].as_u64() {
            config::write_private(
                &path,
                &serde_json::to_vec(
                    &json!({"session_id":id.to_string(),"upload_id":upload,"activity_id":activity_id,"state":"complete"}),
                )?,
            )?;
            println!("Indoor ride synchronized: https://www.strava.com/activities/{activity_id}");
            return Ok(());
        }
        if v["error"].as_str().is_some_and(|e| !e.is_empty()) {
            bail!("Strava rejected the upload; check the upload in Strava (server details hidden)");
        }
        tokio::time::sleep(Duration::from_secs(2)).await;
    }
    println!("Strava is processing this upload. Run the same sync command later to check it; the file will not be uploaded again.");
    Ok(())
}
#[cfg(test)]
mod tests {
    use super::*;
    #[tokio::test]
    async fn http_error_never_echoes_sensitive_body() {
        use std::io::{Read, Write};
        let listener = std::net::TcpListener::bind("127.0.0.1:0").unwrap();
        let address = listener.local_addr().unwrap();
        let worker = std::thread::spawn(move || {
            let (mut s, _) = listener.accept().unwrap();
            let mut buffer = [0; 2048];
            let _ = s.read(&mut buffer);
            s.write_all(b"HTTP/1.1 401 Unauthorized\r\nContent-Length: 17\r\nConnection: close\r\n\r\nsecret-token-test").unwrap();
        });
        let err = response(client().unwrap().get(format!("http://{address}")))
            .await
            .unwrap_err()
            .to_string();
        assert!(err.contains("401"));
        assert!(!err.contains("secret-token"));
        worker.join().unwrap();
    }
}
